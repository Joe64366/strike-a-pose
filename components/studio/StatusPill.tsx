"use client";

import { CircleAlert, LoaderCircle, Pin } from "lucide-react";
import { AnimatePresence, motion } from "motion/react";
import { useEffect, useState } from "react";
import { springSnappy } from "@/lib/motion";
import type { PoseEntry } from "@/lib/poses";
import type { GenerationResult } from "./usePoseGeneration";

const TIMING_VISIBLE_MS = 3500;

/**
 * Answers "what am I looking at?" for the stage, and pins it in one click.
 * Right after the AI finishes, briefly shows how long it took.
 */
export function StatusPill({
  entry,
  onTogglePin,
  result,
}: {
  entry: PoseEntry | null;
  onTogglePin: (id: string) => void;
  result?: GenerationResult | null;
}) {
  const [timing, setTiming] = useState<GenerationResult | null>(null);
  useEffect(() => {
    if (!result) return;
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setTiming(result);
    const t = setTimeout(() => setTiming(null), TIMING_VISIBLE_MS);
    return () => clearTimeout(t);
  }, [result]);

  const key = entry ? `${entry.id}:${entry.status}:${entry.title}` : "default";
  const canPin = entry && entry.status !== "posing";
  const pinned = !!entry?.pinnedAt;
  const showTiming = timing && entry && timing.id === entry.id && entry.status === "ready";

  let icon: React.ReactNode = null;
  let text = "Default pose";
  if (entry?.status === "posing") {
    icon = <LoaderCircle size={14} className="animate-spin text-accent" aria-hidden />;
    text = entry.prompts.length > 1 ? `Refining “${entry.title}”…` : "Posing…";
  } else if (entry?.status === "error") {
    icon = <CircleAlert size={14} className="text-danger" aria-hidden />;
    text = `Couldn't pose “${entry.title}”`;
  } else if (entry) {
    text = entry.title;
  }

  return (
    <motion.div
      layout
      transition={springSnappy}
      className={`material pointer-events-auto flex h-9 max-w-[min(440px,50vw)] items-center overflow-hidden rounded-full ${canPin ? "pr-1 pl-4" : "px-4"}`}
    >
      <AnimatePresence mode="popLayout" initial={false}>
        <motion.span
          key={key}
          layout="position"
          initial={{ opacity: 0, y: 6 }}
          animate={{ opacity: 1, y: 0 }}
          exit={{ opacity: 0, y: -6 }}
          transition={springSnappy}
          role="status"
          aria-live="polite"
          className={`flex min-w-0 items-center gap-2 text-[13px] font-medium ${entry ? "text-label" : "text-label-2"}`}
        >
          {icon}
          <span className="truncate">{text}</span>
        </motion.span>
      </AnimatePresence>
      <AnimatePresence initial={false}>
        {showTiming && (
          <motion.span
            key="timing"
            layout="position"
            initial={{ opacity: 0, width: 0 }}
            animate={{ opacity: 1, width: "auto" }}
            exit={{ opacity: 0, width: 0 }}
            transition={springSnappy}
            className="shrink-0 overflow-hidden pl-1.5 text-[12px] whitespace-nowrap text-label-3 tabular-nums"
            data-tip={timing.provider ? `Generated by ${timing.provider === "groq" ? "Groq" : "Gemini"}` : undefined}
          >
            · {(timing.ms / 1000).toFixed(1)} s
          </motion.span>
        )}
      </AnimatePresence>
      {canPin && (
        <motion.button
          layout="position"
          type="button"
          onClick={() => onTogglePin(entry.id)}
          aria-pressed={pinned}
          aria-label={pinned ? "Unpin pose" : "Pin pose"}
          data-tip={pinned ? "Unpin" : "Pin to top of history"}
          className={`pressable ml-1.5 flex size-7 shrink-0 items-center justify-center rounded-full ${
            pinned ? "text-accent hover:bg-accent-fill" : "text-label-3 hover:bg-fill hover:text-label"
          }`}
        >
          <motion.span
            key={pinned ? "on" : "off"}
            initial={{ scale: 0.6, rotate: pinned ? -30 : 0 }}
            animate={{ scale: 1, rotate: 0 }}
            transition={{ type: "spring", bounce: 0.4, duration: 0.35 }}
            className="flex"
          >
            <Pin size={15} strokeWidth={2.2} fill={pinned ? "currentColor" : "none"} aria-hidden />
          </motion.span>
        </motion.button>
      )}
    </motion.div>
  );
}
